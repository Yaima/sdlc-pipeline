#!/usr/bin/env python3
"""Build the installable tree from core/. Output: dist/ (one tree, copied onto a repo root).

  python3 build.py

Layout of dist/ (verified against the tools' docs on 2026-09-29; see docs/start/*.md):

  AGENTS.md.sdlc              generated pipeline block; install.sh splices it into the repo's AGENTS.md
  CLAUDE.md                   "@AGENTS.md" (Claude Code reads AGENTS.md natively only when CLAUDE.md is absent)
  .agents/skills/<stage>/     stage playbooks as skills: read by Codex, Copilot, Gemini
  .claude/skills/<stage>/     same files: Claude Code does not read .agents/
  .claude/agents/<role>.md    role subagents: Claude Code and Copilot (CLI, VS Code) read this dir
  .claude/hooks/*.sh          guard scripts (Claude, Codex, Copilot, Gemini via the bridge)
  .claude/settings.json       hooks: Claude Code; Copilot CLI/VS Code load it too
  .codex/hooks.json           same scripts wired to Codex hook events
  .codex/agents/<role>.toml   role subagents for Codex
  .codex/config.toml          project_doc_max_bytes (AGENTS.md is long), sandbox
  .gemini/settings.json       context.fileName -> AGENTS.md; BeforeTool hooks through gemini-bridge.sh
  .gemini/agents/<role>.md    role subagents for Gemini
  .github/hooks/sdlc.json     hooks for the Copilot cloud agent (runs on github.com, no .claude/ hooks there)
  .github/agents/<role>.md    role agents for the Copilot cloud agent
  docs/pipeline/              process, rules, roles, stages, templates, enforcement, config template
  docs/start/                 per-tool start guides
"""
import json, pathlib, re, shutil

ROOT = pathlib.Path(__file__).resolve().parent
CORE = ROOT / "core"
DIST = ROOT / "dist"
VERSION = (ROOT / "VERSION").read_text().strip()
ROLES = sorted(p.stem for p in (CORE / "roles").glob("*.md"))
STAGES = ["start", "codebase-map", "grill", "estimate", "prd", "handoff", "implement", "review", "qa", "feature", "roadmap", "retro"]
AGENT_META = json.loads((ROOT / "adapters/claude-code/agents.json").read_text())
STAGE_META = json.loads((ROOT / "adapters/claude-code/stages.json").read_text())

def read(p): return (CORE / p).read_text()
def write(p, text, mode=None):
    p.parent.mkdir(parents=True, exist_ok=True); p.write_text(text)
    if mode: p.chmod(mode)
def desc(s): return STAGE_META.get(s, {}).get("description", "").strip('"')
def role_desc(r):
    b = read(f"roles/{r}.md").split("\n"); return b[2] if b[0].startswith("# Role:") else ""
def role_body(r):
    b = read(f"roles/{r}.md"); return b.split("\n", 3)[3].lstrip() if b.startswith("# Role:") else b

def stage_skill(s):
    """One SKILL.md that every tool accepts: $ARGUMENTS for the argument string, <slug> in paths."""
    body = read(f"stages/{s}.md")
    first = "name" if s == "roadmap" else "slug"
    body = body.replace("{args}", "<args>").replace("{slug}", "<slug>").replace("{name}", "<name>")
    head = (f"Arguments: `$ARGUMENTS`. The first token is `<{first}>`; anything after it is `<args>`. "
            f"If `$ARGUMENTS` is empty, ask for the {first} and stop.\n\n")
    fm = [f"name: {s}", f'description: "{desc(s)}"']
    if STAGE_META.get(s, {}).get("disable-model-invocation"): fm.append("disable-model-invocation: true")
    ah = {"start": "[slug]", "codebase-map": "", "grill": "<slug> <idea>", "prd": "<slug> [idea]", "handoff": "<slug>",
          "implement": "<slug> [task-id]", "review": "<slug>", "qa": "<slug>", "feature": "<slug> [--lite] [idea]",
          "roadmap": "<name> <description>", "retro": "<slug>", "estimate": "<slug>"}[s]
    if ah: fm.append(f'argument-hint: "{ah}"')
    if "allowed-tools" in STAGE_META.get(s, {}): fm.append(f"allowed-tools: {STAGE_META[s]['allowed-tools']}")
    return "---\n" + "\n".join(fm) + "\n---\n\n" + head + body

def rules_block():
    """One line per rule file: its H1 as the summary. Bodies load with the stage skills and roles that cite them."""
    lines = []
    for f in sorted((CORE / "rules").glob("*.md")):
        h1 = next((l[2:].strip() for l in f.read_text().splitlines() if l.startswith("# ")), f.stem)
        lines.append(f"- `docs/pipeline/rules/{f.name}`: {h1}")
    return "\n".join(lines) + "\n"

def agents_block():
    stages = "\n".join(f"| `/{s}` | {desc(s)} |" for s in STAGES)
    roles = "\n".join(f"| `{r}` | {role_desc(r)} |" for r in ROLES)
    return f"""<!-- sdlc:begin {VERSION} (generated by sdlc-pipeline install.sh; edit core/ in the pipeline repo, not this block) -->
## Feature pipeline

Read `docs/pipeline/PROCESS.md` before any pipeline work. Every feature lives in `docs/features/<slug>/`; read its `state.json` before touching it. Stages are skills in `.agents/skills/` (also `.claude/skills/`), invoked as slash commands with the slug as the first argument:

| stage | what it does |
|---|---|
{stages}

Roles run in a fresh context with only the inputs the stage lists (`docs/pipeline/RUNNING-ROLES.md`). They are subagents in `.claude/agents/` (Claude Code, Copilot), `.codex/agents/` (Codex), `.gemini/agents/` (Gemini):

| role | job |
|---|---|
{roles}

Commit, push, and merge are human actions (`commit_mode: human` in `docs/pipeline/pipeline.json`). Agents leave changes in the working tree and end their report with `git status --short`. What each tool enforces vs. asks: `docs/pipeline/ENFORCEMENT.md`.

## Pipeline rules

Five lines every agent follows on every turn:

- Read the code; never recall it. Cite `path:line` for any claim about the repo, and end every report with `## Evidence` (files read, commands with exit codes, things looked for and not found).
- `docs/features/<slug>/ticket.md` is the scope authority. Behavior the ticket does not ask for is an `[ADDS SCOPE]` question for the human, never a default.
- A task starts with a failing test. Test files are read-only for the implementer; a wrong test is a dispute in `tasks.md`, never an edit.
- The reviewer runs the tests itself and reads no implementer notes. Only `code-reviewer` writes a `VERDICT:` line.
- Commit, push, and merge are human actions in `commit_mode: human`. Leave changes in the working tree and end with `git status --short`.

The full rules, loaded by the stages and roles that cite them:

{rules_block()}<!-- sdlc:end -->
"""

def claude_agent(r):
    m = AGENT_META[r]
    fm = [f"name: {r}", f"description: {m.get('description','')}", f"tools: {m.get('tools','Read, Grep, Glob')}",
          f"model: {m.get('model','opus')}", f"maxTurns: {m.get('maxTurns',40)}", "include-custom-instructions: true"]
    hooks = []
    if m.get("guard_mode"):
        hooks.append('    - matcher: "Edit|Write|MultiEdit|NotebookEdit"\n      hooks:\n        - type: command\n          command: "${CLAUDE_PROJECT_DIR}/.claude/hooks/guard-paths.sh %s"' % m["guard_mode"])
    if m.get("reviewer_inputs_guard"):
        hooks.append('    - matcher: "Read"\n      hooks:\n        - type: command\n          command: "${CLAUDE_PROJECT_DIR}/.claude/hooks/guard-reviewer-inputs.sh"')
    if hooks: fm.append("hooks:\n  PreToolUse:\n" + "\n".join(hooks))
    return "---\n" + "\n".join(fm) + "\n---\n\n" + role_body(r)

def toml_str(s): return '"""\n' + s.replace('"""', "'''") + '\n"""'

def codex_agent(r):
    m = AGENT_META[r]
    return (f'name = "{r}"\ndescription = "{m.get("description","").replace(chr(34), chr(39))}"\n'
            f"developer_instructions = {toml_str(role_body(r))}\n")

def gemini_agent(r):
    m = AGENT_META[r]
    return (f"---\nname: {r}\ndescription: \"{m.get('description','').replace(chr(34), chr(39))}\"\nmax_turns: {m.get('maxTurns',40)}\n---\n\n" + role_body(r))

def github_agent(r):
    m = AGENT_META[r]
    tools = "read, search, edit, execute" if r in ("implementer", "test-writer", "qa-engineer") else "read, search, execute" if r == "code-reviewer" else "read, search, edit"
    return (f"---\nname: {r}\ndescription: \"{m.get('description','').replace(chr(34), chr(39))}\"\ntools: [{tools}]\ninclude-custom-instructions: true\n---\n\n" + role_body(r))

def hook_cmd(script): return f'"${{CLAUDE_PROJECT_DIR}}/.claude/hooks/{script}"'

def build():
    shutil.rmtree(DIST, ignore_errors=True)
    # shared docs
    dp = DIST / "docs/pipeline"
    for sub in ["rules", "roles", "stages", "templates", "enforcement"]:
        shutil.copytree(CORE / sub, dp / sub, dirs_exist_ok=True)
    for f in ["PROCESS.md", "ENFORCEMENT.md", "RUNNING-ROLES.md", "pipeline.json"]:
        shutil.copy(CORE / f, dp / f)
    write(dp / "VERSION", VERSION + "\n")
    if (ROOT / "docs/start").exists(): shutil.copytree(ROOT / "docs/start", DIST / "docs/start", dirs_exist_ok=True)
    write(DIST / "docs/features/.gitkeep", "")
    # project instructions
    write(DIST / "AGENTS.md.sdlc", agents_block())
    write(DIST / "AGENTS.md.template", read("PROJECT.md").split("## How work flows here")[0].rstrip() + "\n\n" + agents_block())
    write(DIST / "CLAUDE.md", "@AGENTS.md\n")
    # stage skills, two locations
    for s in STAGES:
        t = stage_skill(s)
        write(DIST / f".agents/skills/{s}/SKILL.md", t)
        write(DIST / f".claude/skills/{s}/SKILL.md", t)
    # roles
    for r in ROLES:
        write(DIST / f".claude/agents/{r}.md", claude_agent(r))
        write(DIST / f".codex/agents/{r}.toml", codex_agent(r))
        write(DIST / f".gemini/agents/{r}.md", gemini_agent(r))
        write(DIST / f".github/agents/{r}.md", github_agent(r))
    # hooks
    for h in (ROOT / "adapters/claude-code/hooks").glob("*.sh"):
        write(DIST / ".claude/hooks" / h.name, h.read_text(), 0o755)
    shutil.copy(ROOT / "adapters/claude-code/settings.json", DIST / ".claude/settings.json")
    codex_hooks = {"hooks": {
        "SessionStart": [{"hooks": [{"type": "command", "command": ".claude/hooks/session-status.sh"}]}],
        "PreToolUse": [
            {"matcher": "^Bash$", "hooks": [{"type": "command", "command": ".claude/hooks/guard-git.sh"}]},
            {"matcher": "^apply_patch$", "hooks": [{"type": "command", "command": ".claude/hooks/guard-paths.sh tests-readonly"}]}],
        "SubagentStop": [{"hooks": [{"type": "command", "command": ".claude/hooks/evidence-gate.sh"}]}]}}
    write(DIST / ".codex/hooks.json", json.dumps(codex_hooks, indent=2) + "\n")
    write(DIST / ".codex/config.toml",
          '# sdlc-pipeline: AGENTS.md (repo facts plus the generated pipeline block) can pass the 32 KiB default.\n'
          'project_doc_max_bytes = 131072\n# Agents edit the working tree and never commit; the guards in .codex/hooks.json enforce the rest.\n'
          'sandbox_mode = "workspace-write"\n')
    gemini = {"context": {"fileName": ["AGENTS.md", "GEMINI.md"]},
              "hooks": {"BeforeTool": [
                  {"matcher": "run_shell_command", "hooks": [{"name": "sdlc-guard-git", "type": "command", "command": "$GEMINI_PROJECT_DIR/.claude/hooks/gemini-bridge.sh guard-git", "timeout": 10000}]},
                  {"matcher": "write_file|replace", "hooks": [{"name": "sdlc-guard-paths", "type": "command", "command": "$GEMINI_PROJECT_DIR/.claude/hooks/gemini-bridge.sh guard-paths tests-readonly", "timeout": 10000}]}]}}
    write(DIST / ".gemini/settings.json", json.dumps(gemini, indent=2) + "\n")
    gh_hooks = {"version": 1, "hooks": {
        "preToolUse": [{"type": "command", "bash": "bash .claude/hooks/guard-git.sh", "timeoutSec": 30},
                       {"type": "command", "bash": "bash .claude/hooks/guard-paths.sh tests-readonly", "timeoutSec": 30}],
        "subagentStop": [{"type": "command", "bash": "bash .claude/hooks/evidence-gate.sh", "timeoutSec": 60}]}}
    write(DIST / ".github/hooks/sdlc.json", json.dumps(gh_hooks, indent=2) + "\n")
    n = sum(1 for _ in DIST.rglob("*") if _.is_file())
    print(f"built dist: {n} files")

if __name__ == "__main__":
    build()
